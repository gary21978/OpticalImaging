Status CudaStatus(cudaError_t status)
{
    if (status != cudaSuccess)
    {
        std::cerr << "CUDA runtime error: " << cudaGetErrorString(status) << "\n";
    }
    return status == cudaSuccess ? Status::kSuccess : Status::kCudaError;
}

void Require(Status status, const char* step)
{
    if (status != Status::kSuccess)
    {
        std::cerr << "ERROR: " << step << " failed: " << StatusToString(status) << "\n";
        std::exit(EXIT_FAILURE);
    }
}

struct DeviceBuffer
{
    Complex* ptr = nullptr;
    ~DeviceBuffer() { SAFEFREE(ptr); }
};

struct Pattern
{
    std::string name;
    std::vector<Complex> eps;
};

bool InCircle(double x, double y, double cx, double cy, double radius)
{
    const double dx = x - cx;
    const double dy = y - cy;
    return dx * dx + dy * dy <= radius * radius;
}

Pattern BuildConcavePolygon(int nx, int ny)
{
    Pattern pattern{"concave_l_polygon", {}};
    pattern.eps.assign(static_cast<size_t>(nx) * ny, make_complex(1.0, 0.0));
    const Complex material = make_complex(6.0, 0.0);
    for (int x = 0; x < nx; ++x)
    {
        for (int y = 0; y < ny; ++y)
        {
            const bool outer = x >= 12 && x < 52 && y >= 12 && y < 52;
            const bool notch = x >= 30 && y >= 30;
            if (outer && !notch)
            {
                pattern.eps[static_cast<size_t>(x) * ny + y] = material;
            }
        }
    }
    return pattern;
}

Pattern BuildCorner(int nx, int ny)
{
    Pattern pattern{"right_angle_corner", {}};
    pattern.eps.assign(static_cast<size_t>(nx) * ny, make_complex(1.0, 0.0));
    const Complex material = make_complex(8.0, 0.0);
    for (int x = 0; x < nx; ++x)
    {
        for (int y = 0; y < ny; ++y)
        {
            if ((x >= 10 && x < 54 && y >= 28 && y < 42) ||
                (x >= 28 && x < 42 && y >= 10 && y < 54))
            {
                pattern.eps[static_cast<size_t>(x) * ny + y] = material;
            }
        }
    }
    return pattern;
}

Pattern BuildMultipleHoles(int nx, int ny)
{
    Pattern pattern{"multiple_holes", {}};
    pattern.eps.assign(static_cast<size_t>(nx) * ny, make_complex(9.0, 0.0));
    for (int x = 0; x < nx; ++x)
    {
        for (int y = 0; y < ny; ++y)
        {
            const bool hole = InCircle(x, y, 20.0, 20.0, 7.0) ||
                              InCircle(x, y, 43.0, 23.0, 8.0) ||
                              InCircle(x, y, 32.0, 44.0, 9.0);
            if (hole)
            {
                pattern.eps[static_cast<size_t>(x) * ny + y] = make_complex(1.0, 0.0);
            }
        }
    }
    return pattern;
}

Pattern BuildTiltedGrating(int nx, int ny)
{
    Pattern pattern{"tilted_grating", {}};
    pattern.eps.assign(static_cast<size_t>(nx) * ny, make_complex(1.0, 0.0));
    const Complex material = make_complex(-80.0, 35.0);
    constexpr double pi = 3.14159265358979323846;
    const double angle = 28.0 * pi / 180.0;
    const double ca = std::cos(angle);
    const double sa = std::sin(angle);
    constexpr double period = 18.0;
    for (int x = 0; x < nx; ++x)
    {
        for (int y = 0; y < ny; ++y)
        {
            double phase = std::fmod(ca * x + sa * y + 10.0 * period, period);
            if (phase < 0.48 * period)
            {
                pattern.eps[static_cast<size_t>(x) * ny + y] = material;
            }
        }
    }
    return pattern;
}

void WriteMatrix(std::ofstream& out,
                 const char* name,
                 const std::vector<Complex>& data,
                 int nx,
                 int ny,
                 bool real_part)
{
    out << name << " = [\n";
    out << std::setprecision(12);
    for (int y = 0; y < ny; ++y)
    {
        for (int x = 0; x < nx; ++x)
        {
            const Complex value = data[static_cast<size_t>(x) * ny + y];
            out << (real_part ? ComplexReal(value) : ComplexImag(value));
            if (x + 1 < nx)
            {
                out << ", ";
            }
        }
        out << ";\n";
    }
    out << "];\n";
}

void WriteMatlab(const std::filesystem::path& path,
                 const Pattern& pattern,
                 const std::vector<Complex>& nx_field,
                 const std::vector<Complex>& ny_field,
                 int nx,
                 int ny)
{
    std::ofstream out(path);
    if (!out)
    {
        std::cerr << "ERROR: cannot open " << path << " for writing\n";
        std::exit(EXIT_FAILURE);
    }

    out << "% Generated by normal_vector_field_test.\n";
    WriteMatrix(out, "eps_real", pattern.eps, nx, ny, true);
    WriteMatrix(out, "nx_field", nx_field, nx, ny, true);
    WriteMatrix(out, "ny_field", ny_field, nx, ny, true);
    out << "[X, Y] = meshgrid(0:" << (nx - 1) << ", 0:" << (ny - 1) << ");\n";
    out << "step = 3;\n";
    out << "figure('Name', '" << pattern.name << "');\n";
    out << "imagesc(eps_real); axis image; set(gca, 'YDir', 'normal'); colormap(gray); hold on;\n";
    out << "quiver(X(1:step:end,1:step:end), Y(1:step:end,1:step:end), "
           "nx_field(1:step:end,1:step:end), ny_field(1:step:end,1:step:end), "
           "0.65, 'color', [0.5, 0.5, 0.5]);\n";
    out << "title('" << pattern.name << " normal vector field');\n";
}

void RunPattern(const Pattern& pattern, int nx, int ny, const std::filesystem::path& out_dir)
{
    DeviceBuffer d_eps;
    DeviceBuffer d_nx;
    DeviceBuffer d_ny;
    const size_t bytes = pattern.eps.size() * sizeof(Complex);
    Require(CudaStatus(cudaMalloc(reinterpret_cast<void**>(&d_eps.ptr), bytes)), "cudaMalloc eps");
    Require(CudaStatus(cudaMemcpy(d_eps.ptr, pattern.eps.data(), bytes, cudaMemcpyHostToDevice)),
            "copy eps");

    RCWA rcwa(1.0, 1, 1, 1.0, 1.0);
    Require(rcwa.GenerateNormalVectorField(
                d_eps.ptr, nx, ny, static_cast<Real>(1e-6), &d_nx.ptr, &d_ny.ptr),
            "GenerateNormalVectorField");
    Require(CudaStatus(cudaDeviceSynchronize()), "GenerateNormalVectorField synchronize");

    std::vector<Complex> nx_field(pattern.eps.size());
    std::vector<Complex> ny_field(pattern.eps.size());
    Require(CudaStatus(cudaMemcpy(nx_field.data(), d_nx.ptr, bytes, cudaMemcpyDeviceToHost)),
            "copy nx field");
    Require(CudaStatus(cudaMemcpy(ny_field.data(), d_ny.ptr, bytes, cudaMemcpyDeviceToHost)),
            "copy ny field");

    double min_norm = 10.0;
    double max_norm = 0.0;
    double sum_norm = 0.0;
    for (size_t i = 0; i < nx_field.size(); ++i)
    {
        const double vx = static_cast<double>(ComplexReal(nx_field[i]));
        const double vy = static_cast<double>(ComplexReal(ny_field[i]));
        const double norm = std::sqrt(vx * vx + vy * vy);
        if (!std::isfinite(norm) || norm > 1.01)
        {
            std::cerr << "ERROR: invalid normal magnitude in " << pattern.name << "\n";
            std::exit(EXIT_FAILURE);
        }
        min_norm = std::min(min_norm, norm);
        max_norm = std::max(max_norm, norm);
        sum_norm += norm;
    }

    WriteMatlab(out_dir / (pattern.name + ".m"), pattern, nx_field, ny_field, nx, ny);
    std::cout << std::setw(20) << pattern.name
              << "  min|n|=" << std::fixed << std::setprecision(4) << min_norm
              << "  mean|n|=" << sum_norm / static_cast<double>(nx_field.size())
              << "  max|n|=" << max_norm << "\n";
}
} // namespace

int main()
{
    constexpr int nx = 64;
    constexpr int ny = 64;
    const std::filesystem::path out_dir = "normal_vector_outputs";
    std::filesystem::create_directories(out_dir);

    const std::vector<Pattern> patterns = {
        BuildConcavePolygon(nx, ny),
        BuildCorner(nx, ny),
        BuildMultipleHoles(nx, ny),
        BuildTiltedGrating(nx, ny),
    };

    std::cout << "Normal vector field diagnostics\n";
    for (const Pattern& pattern : patterns)
    {
        RunPattern(pattern, nx, ny, out_dir);
    }
    std::cout << "MATLAB files written to " << out_dir << "\n";
    return EXIT_SUCCESS;
}
